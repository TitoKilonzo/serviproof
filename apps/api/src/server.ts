import dotenv from 'dotenv';
dotenv.config();
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import authRoutes from './routes/auth.js';
import appRoutes from './routes/app.js';
import evidenceRoutes from './routes/evidence.js';
import { authenticate } from './middleware/auth.js';
import { pool } from './db.js';
import { startScheduler } from './scheduler.js';
const app=express();
const origin=process.env.WEB_ORIGIN??'http://localhost:5173';
const allowedOrigins=origin.split(',').map(x=>x.trim());
app.disable('x-powered-by');
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'},contentSecurityPolicy:process.env.NODE_ENV==='production'?undefined:false}));
app.use(cors({origin:allowedOrigins,credentials:true,methods:['GET','POST','PATCH','PUT','DELETE','OPTIONS'],allowedHeaders:['Content-Type','Authorization']}));
app.use((req,res,next)=>{if(['POST','PUT','PATCH','DELETE'].includes(req.method)){const requestOrigin=req.get('origin');if(requestOrigin&&!allowedOrigins.includes(requestOrigin))return res.status(403).json({error:'Request origin is not permitted.'});}next();});
app.use(express.json({limit:'1mb'}));app.use(express.urlencoded({extended:false,limit:'1mb'}));app.use(cookieParser());
app.get('/api/health',async(_req,res)=>{try{await pool.query('SELECT 1');res.json({status:'ok',service:'ServiProof API',database:'connected',timestamp:new Date().toISOString()});}catch{res.status(503).json({status:'degraded',service:'ServiProof API',database:'unavailable'});}});
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false,message:{error:'Too many attempts. Please try again later.'}}),authRoutes);
app.use('/api',authenticate,appRoutes);
app.use('/api',authenticate,evidenceRoutes);
app.use((req,res)=>res.status(404).json({error:`Route ${req.method} ${req.path} not found.`}));
app.use((error:any,_req:express.Request,res:express.Response,_next:express.NextFunction)=>{console.error(error);if(error?.code==='LIMIT_FILE_SIZE')return res.status(413).json({error:`File exceeds the ${process.env.MAX_UPLOAD_MB??10} MB limit.`});if(error?.code==='23505')return res.status(409).json({error:'A record with these details already exists.'});if(error?.code==='23503')return res.status(400).json({error:'This record is linked to another record and cannot be changed.'});res.status(500).json({error:process.env.NODE_ENV==='production'?'Something went wrong. Please try again.':error?.message??'Internal server error.'});});
const port=Number(process.env.PORT??4000);
const server=app.listen(port,()=>{console.log(`ServiProof API listening on :${port}`);startScheduler();});
const shutdown=async()=>{server.close(async()=>{await pool.end();process.exit(0);});setTimeout(()=>process.exit(1),10000).unref();};
process.on('SIGTERM',shutdown);process.on('SIGINT',shutdown);
